    `updated_at`       DATETIME     NOT NULL               COMMENT '更新时间(UTC)',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_freeze_no` (`freeze_no`),
    KEY `idx_target_type_id` (`target_type`, `target_id`),
    KEY `idx_target_no` (`target_no`),
    KEY `idx_freeze_status` (`freeze_status`),
    KEY `idx_freeze_mode` (`freeze_mode`),
    KEY `idx_apply_user_id` (`apply_user_id`)
