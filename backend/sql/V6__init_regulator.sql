CREATE TABLE `risk_event` (
    `id`               BIGINT       NOT NULL               COMMENT '主键（雪花ID）',
    `risk_no`          VARCHAR(64)  NOT NULL               COMMENT '风险编号',
    `target_type`      VARCHAR(30)  NOT NULL               COMMENT '目标类型',
    `target_id`        BIGINT       NOT NULL               COMMENT '目标ID',
    `target_no`        VARCHAR(64)           DEFAULT NULL  COMMENT '目标编号',
    `status`           VARCHAR(30)  NOT NULL               COMMENT '风险状态',
    `risk_level`       VARCHAR(20)  NOT NULL               COMMENT '风险等级(LOW/MEDIUM/HIGH/CRITICAL)',
    `risk_type`        VARCHAR(30)  NOT NULL               COMMENT '风险类型',
    `risk_description` TEXT                  DEFAULT NULL  COMMENT '风险描述',
    `reporter_id`      BIGINT                DEFAULT NULL  COMMENT '报告人ID',
    `reporter_role`    VARCHAR(30)           DEFAULT NULL  COMMENT '报告人角色',
    `report_time`      DATETIME              DEFAULT NULL  COMMENT '报告时间(UTC)',
    `reason_code`      VARCHAR(64)           DEFAULT NULL  COMMENT '原因码',
    `result_summary`   VARCHAR(512)          DEFAULT NULL  COMMENT '结果摘要',
    `resolve_time`     DATETIME              DEFAULT NULL  COMMENT '解决时间(UTC)',
    `deleted_flag`     TINYINT      NOT NULL DEFAULT 0     COMMENT '删除标记 0-未删除 1-已删除',
    `created_at`       DATETIME     NOT NULL               COMMENT '创建时间(UTC)',
    `updated_at`       DATETIME     NOT NULL               COMMENT '更新时间(UTC)',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_risk_no` (`risk_no`),
    KEY `idx_target_type_id` (`target_type`, `target_id`),
    KEY `idx_target_no` (`target_no`),
    KEY `idx_status` (`status`),
    KEY `idx_risk_level` (`risk_level`),
    KEY `idx_risk_type` (`risk_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='风险事件表';

CREATE TABLE `freeze_record` (
