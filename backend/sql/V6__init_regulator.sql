    `freeze_mode`      VARCHAR(30)  NOT NULL               COMMENT '冻结模式(REVIEW_REQUIRED/REGULATOR_DIRECT)',
    `review_status`    VARCHAR(20)           DEFAULT NULL  COMMENT '审核状态',
