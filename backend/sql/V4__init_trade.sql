CREATE TABLE IF NOT EXISTS `license_template` (
    `id`                BIGINT       NOT NULL               COMMENT '主键（雪花ID）',
    `template_name`     VARCHAR(128) NOT NULL               COMMENT '模板名称',
    `template_code`     VARCHAR(64)  NOT NULL               COMMENT '模板编码',
    `license_type`      VARCHAR(30)  NOT NULL               COMMENT '授权类型(PERSONAL_USE/COMMERCIAL_USE/EXCLUSIVE)',
    `scope_description` TEXT                  DEFAULT NULL  COMMENT '范围描述',
    `duration_days`     INT                   DEFAULT NULL  COMMENT '有效天数',
    `price_amount`      BIGINT       NOT NULL               COMMENT '价格（分）',
    `currency`          VARCHAR(10)  NOT NULL DEFAULT 'CNY' COMMENT '币种',
    `status`            VARCHAR(20)  NOT NULL               COMMENT '状态(ACTIVE/INACTIVE)',
    `description`       VARCHAR(512)          DEFAULT NULL  COMMENT '描述',
    `deleted_flag`      TINYINT      NOT NULL DEFAULT 0     COMMENT '删除标记 0-未删除 1-已删除',
    `created_at`        DATETIME     NOT NULL               COMMENT '创建时间(UTC)',
    `updated_at`        DATETIME     NOT NULL               COMMENT '更新时间(UTC)',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_template_code` (`template_code`),
    KEY `idx_license_type` (`license_type`),
    KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='授权模板表';

CREATE TABLE IF NOT EXISTS `work_listing` (
    `id`                  BIGINT       NOT NULL               COMMENT '主键（雪花ID）',
    `listing_no`          VARCHAR(64)  NOT NULL               COMMENT '上架编号',
    `work_id`             BIGINT       NOT NULL               COMMENT '作品ID',
    `work_no`             VARCHAR(64)  NOT NULL               COMMENT '作品编号',
    `creator_account_id`  BIGINT       NOT NULL               COMMENT '创作者账户ID',
    `license_template_id` BIGINT                DEFAULT NULL  COMMENT '授权模板ID',
    `license_type`        VARCHAR(30)  NOT NULL               COMMENT '授权类型',
    `price_amount`        BIGINT       NOT NULL               COMMENT '价格（分）',
    `currency`            VARCHAR(10)  NOT NULL DEFAULT 'CNY' COMMENT '币种',
    `status`              VARCHAR(30)  NOT NULL               COMMENT '上架状态(PENDING_REVIEW/LISTED/UNLISTED/REJECTED/FROZEN)',
    `review_status`       VARCHAR(20)           DEFAULT NULL  COMMENT '审核状态',
    `reviewer_id`         BIGINT                DEFAULT NULL  COMMENT '审核人ID',
    `review_comment`      VARCHAR(512)          DEFAULT NULL  COMMENT '审核意见',
    `list_time`           DATETIME              DEFAULT NULL  COMMENT '上架时间(UTC)',
    `unlist_time`         DATETIME              DEFAULT NULL  COMMENT '下架时间(UTC)',
    `scope_description`   TEXT                  DEFAULT NULL  COMMENT '范围描述',
    `duration_days`       INT                   DEFAULT NULL  COMMENT '有效天数',
    `version`             INT          NOT NULL DEFAULT 0     COMMENT '乐观锁版本号',
    `deleted_flag`        TINYINT      NOT NULL DEFAULT 0     COMMENT '删除标记 0-未删除 1-已删除',
    `created_at`          DATETIME     NOT NULL               COMMENT '创建时间(UTC)',
    `updated_at`          DATETIME     NOT NULL               COMMENT '更新时间(UTC)',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_listing_no` (`listing_no`),
    KEY `idx_work_id` (`work_id`),
    KEY `idx_work_no` (`work_no`),
    KEY `idx_creator_account_id` (`creator_account_id`),
    KEY `idx_status` (`status`),
    KEY `idx_license_type` (`license_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='作品上架表';

