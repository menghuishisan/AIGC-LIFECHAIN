    `listing_id`          BIGINT       NOT NULL               COMMENT '上架记录ID',
    `listing_no`          VARCHAR(64)  NOT NULL               COMMENT '上架编号',
    `buyer_account_id`    BIGINT       NOT NULL               COMMENT '买方账户ID',
    `buyer_subject_id`    BIGINT       NOT NULL               COMMENT '买方主体ID',
